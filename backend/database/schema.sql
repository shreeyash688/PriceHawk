-- PriceHawk database schema for Supabase (PostgreSQL).
-- Run once in Supabase: Dashboard -> SQL Editor -> paste this file -> Run.
-- Safe to re-run ("if not exists").

create table if not exists products (
    id               bigint generated by default as identity primary key,
    title            text        not null,
    url              text        not null,               -- normalized product URL (decides the currency)
    notify_email     text        not null,               -- who gets the alert email
    current_price    numeric(12, 2) not null check (current_price > 0),
    target_price     numeric(12, 2) not null check (target_price > 0),
    tracking_active  boolean     not null default true,  -- false = paused
    alert_sent       boolean     not null default false, -- true = email already sent (stops spam)
    created_at       timestamptz not null default now(),
    last_checked_at  timestamptz,
    last_error       text,                               -- last scrape problem, if any
    unique (url, notify_email)                           -- one person can't track the same product twice,
                                                         -- but different people can
);

create table if not exists price_history (
    id          bigint generated by default as identity primary key,
    product_id  bigint      not null references products(id) on delete cascade,
    price       numeric(12, 2) not null,
    checked_at  timestamptz not null default now()
);

create index if not exists idx_history_product on price_history(product_id);
create index if not exists idx_products_email  on products(notify_email);

-- The Flask backend uses the server-side (service role) key, which bypasses RLS.
-- Turning RLS on with no policies blocks the public "anon" key from reading emails.
alter table products      enable row level security;
alter table price_history enable row level security;
